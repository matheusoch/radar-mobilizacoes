-- Traffic attribution and conversion funnel analytics.
alter table public.page_views
  add column if not exists traffic_source text not null default 'Direto / desconhecido',
  add column if not exists referrer_host text,
  add column if not exists utm_source text,
  add column if not exists utm_medium text,
  add column if not exists utm_campaign text,
  add column if not exists session_id text;

create table if not exists public.analytics_events (
  id bigint generated by default as identity primary key,
  visitor_id uuid not null,
  event_name text not null check (event_name in (
    'signup_started','signup_completed','email_alert_opt_in',
    'nearby_clicked','nearby_viewed','login_completed','digest_preferences_saved'
  )),
  traffic_source text not null default 'Direto / desconhecido',
  utm_source text,
  utm_medium text,
  utm_campaign text,
  session_id text,
  created_at timestamptz not null default now()
);

alter table public.analytics_events enable row level security;
revoke all on public.analytics_events from public, anon, authenticated;
grant insert on public.analytics_events to anon, authenticated;
grant usage, select on sequence public.analytics_events_id_seq to anon, authenticated;

drop policy if exists analytics_events_insert_public on public.analytics_events;
create policy analytics_events_insert_public
  on public.analytics_events for insert to anon, authenticated
  with check (
    event_name in (
      'signup_started','signup_completed','email_alert_opt_in',
      'nearby_clicked','nearby_viewed','login_completed','digest_preferences_saved'
    )
  );

create index if not exists analytics_events_created_at_idx on public.analytics_events(created_at desc);
create index if not exists analytics_events_event_name_created_at_idx on public.analytics_events(event_name, created_at desc);
create index if not exists analytics_events_source_created_at_idx on public.analytics_events(traffic_source, created_at desc);
create index if not exists page_views_source_created_at_idx on public.page_views(traffic_source, created_at desc);

create or replace function public.get_admin_acquisition_metrics()
returns jsonb
language plpgsql
stable
security definer
set search_path = public, auth
as $$
begin
  if auth.uid() is null or not exists (
    select 1 from public.admin_users au where au.user_id = auth.uid()
  ) then
    raise exception 'Acesso restrito à equipe administrativa' using errcode = '42501';
  end if;

  return jsonb_build_object(
    'sources_30d', coalesce((
      select jsonb_agg(jsonb_build_object('source', source, 'views', views, 'visitors', visitors)
                       order by views desc)
      from (
        select coalesce(nullif(traffic_source,''),'Direto / desconhecido') as source,
               count(*) as views, count(distinct visitor_id) as visitors
        from public.page_views
        where created_at >= now() - interval '30 days'
        group by 1
        order by count(*) desc
        limit 10
      ) s
    ), '[]'::jsonb),
    'conversions_30d', coalesce((
      select jsonb_object_agg(event_name, total)
      from (
        select event_name, count(*) as total
        from public.analytics_events
        where created_at >= now() - interval '30 days'
        group by event_name
      ) c
    ), '{}'::jsonb),
    'returning_visitors_30d', (
      select count(*) from (
        select visitor_id from public.page_views
        where created_at >= now() - interval '30 days'
        group by visitor_id having count(*) > 1
      ) returning_visitors
    ),
    'sessions_30d', (select count(distinct session_id) from public.page_views
                     where created_at >= now() - interval '30 days' and session_id is not null),
    'campaigns_30d', coalesce((
      select jsonb_agg(jsonb_build_object('campaign', campaign, 'views', views, 'visitors', visitors)
                       order by views desc)
      from (
        select utm_campaign as campaign, count(*) as views, count(distinct visitor_id) as visitors
        from public.page_views
        where created_at >= now() - interval '30 days' and nullif(utm_campaign,'') is not null
        group by utm_campaign order by count(*) desc limit 10
      ) c
    ), '[]'::jsonb)
  );
end;
$$;

revoke all on function public.get_admin_acquisition_metrics() from public, anon;
grant execute on function public.get_admin_acquisition_metrics() to authenticated;
